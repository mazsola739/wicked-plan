// Prints a compact project map for the agent at session start (SessionStart hook in .claude/settings.json),
// so a new session does not have to explore the repo. CLAUDE.md is loaded anyway, so this only adds what changes.
import { execSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const DOCS = join(ROOT, 'docs');
/** Pages longer than this list their sections with line numbers. */
const BIG_PAGE = 6000;

const run = (cmd) => {
  try {
    return execSync(cmd, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], timeout: 10000 }).trim();
  } catch {
    return '';
  }
};

const read = (path) => (existsSync(path) ? readFileSync(path, 'utf8') : '');

// The docs index: the table rows of docs/README.md, as "path (title): what it is".
const docs = read(join(DOCS, 'README.md'))
  .split('\n')
  .filter((line) => /^\| \[/.test(line))
  .map((line) =>
    line
      .trim()
      .replace(/\[([^\]]+)\]\(([^)]+)\)/, 'docs/$2 ($1)')
      .replace(/^\| /, '- ')
      .replace(/ \| /, ': ')
      .replace(/ \|$/, ''),
  );

// Big pages list their sections, so the agent can read one section (offset/limit) instead of the whole page.
const sections = readdirSync(DOCS)
  .filter((name) => name.endsWith('.md') && name !== 'README.md')
  .flatMap((name) => {
    const text = read(join(DOCS, name));
    if (text.length < BIG_PAGE) return [];
    const heads = text.split('\n').flatMap((line, i) => (line.startsWith('## ') ? [`${line.slice(3, 34).trim()}:${i + 1}`] : []));
    return [`- docs/${name}: ${heads.join(', ')}`];
  });

const workspaces = ['apps', 'packages']
  .filter((parent) => existsSync(join(ROOT, parent)))
  .flatMap((parent) =>
    readdirSync(join(ROOT, parent), { withFileTypes: true })
      .filter((d) => d.isDirectory() && existsSync(join(ROOT, parent, d.name, 'package.json')))
      .map((d) => `${parent}/${d.name}/`),
  );

const status = run('git status --short').split('\n').filter(Boolean);
const out = [
  '# Wicked Plan: project map (generated by scripts/project-context.mjs)',
  `Workspaces: ${workspaces.join(' ')}`,
  'Commands (repo root, bun): `bun run dev` (page on 5173), `bun run wasm`, `bun run test` (cargo; not `bun test`), `bun run typecheck`, `bun run lint`, `bun run map <folder>` (one line per file with its exports). Details: docs/dev.md.',
  '## Docs (read only the page for the area you change)',
  ...(docs.length ? docs : ['(docs/README.md has no index)']),
  '## Sections of the big pages (name:line; read with offset/limit)',
  ...(sections.length ? sections : ['(none)']),
  `## Git: ${run('git branch --show-current')}, ${status.length} uncommitted file(s)${status.length ? " (other sessions' work may be among them; stage only your own files)" : ''}`,
];
console.log(out.join('\n'));
